from __future__ import annotations

import json
from pathlib import Path

from .git_sync import workspace_git_status
from .store import GraphStore


def _short(value: str, n: int = 12) -> str:
    return (value or "")[:n] or "n/a"


def export_markdown(root: Path, store: GraphStore, out: Path | None = None) -> Path:
    """Export a compact, Git-reviewable project summary. The full graph remains in SQLite."""
    root = Path(root).resolve()
    out = out or root / "PROJECT_GRAPH.md"
    stats = store.stats()
    git = workspace_git_status(root)
    repos = store.repo_stats()
    top = store.top_nodes(limit=80)
    events = store.recent_events(30)
    team_db = root / ".repograph" / "cache" / "team_graph.db"
    team_stats = GraphStore(team_db).stats() if team_db.exists() else {"files": 0, "nodes": 0, "edges": 0, "node_kinds": {}, "edge_kinds": {}}

    lines = [
        "# Project Graph",
        "",
        "<!-- Generated by RepoGraph. Compact team summary; full symbol graph is local SQLite. -->",
        "",
        f"- Workspace: `{root.name}`",
        f"- Local repositories: **{len(repos)}**",
        f"- Local files: **{stats['files']}**",
        f"- Local nodes: **{stats['nodes']}**",
        f"- Local edges: **{stats['edges']}**",
        f"- Team/remote files: **{team_stats['files']}**",
        f"- Team/remote nodes: **{team_stats['nodes']}**",
        f"- Team/remote edges: **{team_stats['edges']}**",
        "",
        "> Do not attach this file as the primary AI context. Copilot/agents should query RepoGraph through MCP with a token budget.",
        "",
        "## Repository Status",
        "",
        "| Repository | Local branch | Local commit | Remote ref | Remote commit | Ahead | Behind | Working changes |",
        "|---|---|---|---|---|---:|---:|---:|",
    ]
    by_repo = {r.get("repo"): r for r in git.get("repositories", [])}
    for r in repos:
        g = by_repo.get(r["repo"], {})
        lines.append(
            f"| `{r['repo']}` | `{g.get('branch') or 'n/a'}` | `{_short(g.get('commit',''))}` | "
            f"`{g.get('remote_ref') or 'n/a'}` | `{_short(g.get('remote_commit',''))}` | {g.get('ahead',0)} | {g.get('behind',0)} | {len(g.get('changed',[]))} |"
        )

    lines += ["", "## Graph by Repository", "", "| Repository | Files | Nodes | Edges |", "|---|---:|---:|---:|"]
    for r in repos:
        lines.append(f"| `{r['repo']}` | {r['files']} | {r['nodes']} | {r['edges']} |")

    lines += ["", "## Relationship Summary", "", "| Relation | Count |", "|---|---:|"]
    for kind, count in stats.get("edge_kinds", {}).items():
        lines.append(f"| `{kind}` | {count} |")

    lines += [
        "",
        "## High-Connectivity Symbols",
        "",
        "These are useful architectural entry points; detailed neighborhoods are retrieved via MCP.",
        "",
        "| Repository | Kind | Symbol | Location | Degree |",
        "|---|---|---|---|---:|",
    ]
    for n in top:
        sig = (n.get("signature") or n["name"]).replace("|", "\\|").replace("\n", " ")[:120]
        lines.append(f"| `{n['repo']}` | `{n['kind']}` | `{sig}` | `{n['path']}:{n['line']}` | {n.get('degree',0)} |")

    working = []
    for repo in git.get("repositories", []):
        for c in repo.get("changed", []):
            working.append((repo.get("repo", "?"), c))
    lines += ["", "## Local Working Tree", ""]
    if working:
        for repo, c in working[:200]:
            lines.append(f"- `{repo}` `{c.get('status','?')}` `{c.get('path','')}`")
    else:
        lines.append("All discovered repositories have clean working trees.")

    lines += ["", "## Recent Graph Events", ""]
    if events:
        for e in events:
            details = e.get("details_json") or "{}"
            try:
                d = json.loads(details)
                summary = json.dumps(d, separators=(",", ":"))[:180]
            except Exception:
                summary = str(details)[:180]
            lines.append(f"- `{e['ts']}` **{e['event_type']}** `{e['path']}` — `{summary}`")
    else:
        lines.append("No graph events recorded yet.")

    lines += [
        "",
        "## AI Retrieval Policy",
        "",
        "- Use `graph_search` to locate a symbol or file.",
        "- Use `symbol_context` with a token budget (default 3000) before opening broad sets of files.",
        "- Use `impact` for blast-radius analysis.",
        "- Use `team_symbol_context` / `team_impact` for the latest fetched remote-team graph.",
        "- The complete detailed graphs are `.repograph/cache/graph.db` and `.repograph/cache/team_graph.db` and are not committed.",
    ]

    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out
